// Helper: get every project for a given category slug.
export function getProjectsByCategory(categorySlug) {
  return projects.filter((p) => p.category === categorySlug);
}

// Helper: get a single project by its slug (used on the detail page).
// Slugs are unique across all projects, so no category is needed —
// this powers the flat /project/<slug> route.
export function getProjectBySlug(slug) {
  return projects.find((p) => p.slug === slug);
}
